"""
TestSphere-AI — The generated suite as Playwright files in the app's repository.

After a run, the browser tests TestSphere trusts for a project (they passed this
run and are not quarantined) are written as a small, self-contained Playwright
project under ``testsphere/``:

    testsphere/package.json            @playwright/test, nothing else
    testsphere/playwright.config.ts    baseURL from BASE_URL (default: the app URL)
    testsphere/tests/<group>.spec.ts   one file per kind of test (smoke, journeys, ...)
    testsphere/README.md               how to run them
    .github/workflows/testsphere.yml   GitHub only: runs them on push and pull request

so the team keeps the tests even without TestSphere, and its own CI runs them.
Pure functions: the runner decides when to build, store and propose them.
"""

from __future__ import annotations

import difflib
import hashlib
import json
from typing import Any
from urllib.parse import urlsplit

from app.services.test_studio import to_playwright

ROOT = "testsphere"
WORKFLOW = ".github/workflows/testsphere.yml"
PLAYWRIGHT_VERSION = "1.49.1"

# Which file a test goes in, from its category
_GROUPS = {
    "smoke": "smoke", "content": "content", "link": "pages", "route": "pages",
    "functional": "journeys", "ai": "journeys", "auth": "auth", "form": "forms", "negative": "forms",
}


def _group(tc: dict[str, Any]) -> str:
    category = str(tc.get("category") or "").lower()
    if category.startswith(("auth", "login", "signup")):
        return "auth"
    return _GROUPS.get(category, "other")


def eligible(test_cases: list[dict[str, Any]], results: list[dict[str, Any]],
             steps_of: Any) -> list[tuple[dict[str, Any], list[dict[str, Any]]]]:
    """(test case, steps) of the tests worth committing: they passed (or healed)
    this run, are not quarantined or retired, and have steps to export.  Tests
    that came from the repository are already there."""
    passed = {r["test_case_id"] for r in results if r.get("status") in ("PASSED", "HEALED")}
    out = []
    for tc in test_cases:
        if tc["id"] not in passed or tc.get("quarantined") or tc.get("retired"):
            continue
        if str(tc.get("external_id") or "").startswith("repo-"):
            continue
        steps = steps_of(tc)
        if steps:
            out.append((tc, steps))
    return out


def _config(base_url: str) -> str:
    return f"""import {{ defineConfig, devices }} from '@playwright/test';

// Generated by TestSphere AI. BASE_URL points the suite at another deployment.
export default defineConfig({{
  testDir: './tests',
  timeout: 30_000,
  retries: process.env.CI ? 1 : 0,
  reporter: process.env.CI ? [['list'], ['html', {{ open: 'never' }}]] : 'list',
  use: {{
    baseURL: process.env.BASE_URL || {json.dumps(base_url)},
    trace: 'retain-on-failure',
    screenshot: 'only-on-failure',
  }},
  projects: [{{ name: 'chromium', use: {{ ...devices['Desktop Chrome'] }} }}],
}});
"""


def _package() -> str:
    return json.dumps({
        "name": "testsphere-browser-tests", "private": True,
        "scripts": {"test": "playwright test"},
        "devDependencies": {"@playwright/test": PLAYWRIGHT_VERSION},
    }, indent=2) + "\n"


def _workflow(base_url: str) -> str:
    return f"""# Generated by TestSphere AI: runs the browser tests in testsphere/
name: TestSphere browser tests

on:
  push:
    branches: [main, master]
  pull_request:
  workflow_dispatch:

permissions:
  contents: read

jobs:
  browser-tests:
    runs-on: ubuntu-latest
    timeout-minutes: 20
    defaults:
      run:
        working-directory: testsphere
    env:
      BASE_URL: ${{{{ vars.TESTSPHERE_BASE_URL || '{base_url}' }}}}
    steps:
      - uses: actions/checkout@v4
      - uses: actions/setup-node@v4
        with:
          node-version: 20
      - run: npm install --no-audit --no-fund
      - run: npx playwright install --with-deps chromium
      - run: npx playwright test
      - uses: actions/upload-artifact@v4
        if: failure()
        with:
          name: playwright-report
          path: testsphere/playwright-report
          retention-days: 14
"""


def _readme(base_url: str, groups: dict[str, int]) -> str:
    listed = "\n".join(f"- `tests/{g}.spec.ts`: {n} test(s)" for g, n in sorted(groups.items()))
    return f"""# Browser tests (generated by TestSphere AI)

Plain [Playwright](https://playwright.dev) tests for {base_url}. TestSphere
regenerates these files as the app changes; edit them freely, but a later
TestSphere pull request may overwrite this folder.

{listed}

```bash
npm install
npx playwright install chromium
BASE_URL={base_url} npx playwright test
```
"""


def build(test_cases: list[dict[str, Any]], results: list[dict[str, Any]], *, base_url: str, steps_of: Any,
          github: bool) -> dict[str, Any] | None:
    """The suite's files ``{path: content}`` and what is in it, or None when no
    test qualifies."""
    chosen = eligible(test_cases, results, steps_of)
    if not chosen:
        return None
    by_group: dict[str, list[str]] = {}
    seen_names: dict[str, int] = {}
    for tc, steps in sorted(chosen, key=lambda pair: pair[0]["id"]):
        name = str(tc.get("name") or f"Test {tc['id']}")
        seen_names[name] = seen_names.get(name, 0) + 1
        if seen_names[name] > 1:  # Playwright refuses two tests of one name in a file
            name = f"{name} ({seen_names[name]})"
        by_group.setdefault(_group(tc), []).append(to_playwright(name, steps, base_url=base_url, standalone=False))
    files = {
        f"{ROOT}/package.json": _package(),
        f"{ROOT}/playwright.config.ts": _config(base_url),
        f"{ROOT}/README.md": _readme(base_url, {g: len(b) for g, b in by_group.items()}),
    }
    for group, blocks in by_group.items():
        header = ("import { test, expect } from '@playwright/test';\n\n"
                  f"// Generated by TestSphere AI for {base_url}\n\n")
        files[f"{ROOT}/tests/{group}.spec.ts"] = header + "\n\n".join(blocks) + "\n"
    if github:
        files[WORKFLOW] = _workflow(base_url)
    verified = sum(1 for tc, _ in chosen if (tc.get("acceptance") or {}).get("status") == "verified")
    return {"files": files, "tests": len(chosen), "verified": verified, "groups": sorted(by_group),
            "workflow": github, "hash": suite_hash(files)}


def suite_hash(files: dict[str, str]) -> str:
    return hashlib.sha256(json.dumps(sorted(files.items())).encode()).hexdigest()[:16]


def diff(path: str, old: str | None, new: str) -> str:
    """A unified diff that ``git apply`` accepts, also for a new file."""
    if old == new:
        return ""
    a = old.splitlines(keepends=True) if old is not None else []
    b = new.splitlines(keepends=True)
    head = "" if old is not None else f"diff --git a/{path} b/{path}\nnew file mode 100644\n"
    body = "".join(difflib.unified_diff(a, b, fromfile=f"a/{path}" if old is not None else "/dev/null",
                                        tofile=f"b/{path}"))
    return head + body


def is_github(repo: str | None) -> bool:
    return (urlsplit(repo or "").hostname or "").lower() == "github.com"
